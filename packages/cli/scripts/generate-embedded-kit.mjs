// Generate src/kit/kit-embedded.generated.ts — a map of every kit asset the CLI
// needs at runtime. The compiled Bun binary carries this map and self-extracts
// it to a cache dir on first run, so the single binary is fully self-contained
// (no sibling kit/ on disk to ship).
//
// Keys mirror the flat published layout relative to a "flat root":
//   kit/skills/…, kit/agents/…, kit/hooks/…, portable-manifest.json, …
// Run from the binary build. Deterministic (sorted) for stable diffs.
//
// Text assets are embedded as strings; everything else as base64, because a
// font or image that round-trips through a utf8 string comes out as U+FFFD.
//
// An asset whose payload shrinks appreciably under gzip is embedded compressed
// instead. Every binary carries this map, so kit growth is binary growth, and
// the build refuses a binary over its size ceiling — compressing the heavy
// assets keeps the kit fully self-contained rather than trading offline use
// for a smaller download. Small text assets stay verbatim: turning a readable
// line of Markdown into base64 to save a few bytes only costs review clarity.

import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { IGNORE_DIRS, IGNORE_FILES, isTextFile } from "../src/install/install-types.ts";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(pkgDir, "..", "..");
const kitDir = join(repoRoot, "kit");
const outFile = join(pkgDir, "src", "kit", "kit-embedded.generated.ts");

// Never embed credential material, even if someone drops it into kit/. The
// installer's IGNORE_FILES covers `.env` exactly; these patterns also catch the
// variants and key files that would otherwise be baked into a shipped binary.
const SECRET_PATTERNS = [/^\.env(\..+)?$/, /\.pem$/, /\.p12$/, /^id_[a-z0-9]+$/, /\.key$/];
// `.env.example` and friends are templates the kit deliberately ships — the
// same distinction the privacy-block hook draws.
const TEMPLATE_ENV = /^\.env\.(example|sample|template)$/;

function isSecret(name) {
  if (TEMPLATE_ENV.test(name)) return false;
  return SECRET_PATTERNS.some((rx) => rx.test(name));
}

/** Recursively collect kit assets under `dir`, keyed by their path relative to `base`. */
function collect(dir, base, acc) {
  for (const entry of readdirSync(dir).sort()) {
    const abs = join(dir, entry);
    // lstat, not stat: a symlink must be classified as a symlink rather than as
    // whatever it points at, or a link out of the tree would embed a file the
    // kit does not own.
    const st = lstatSync(abs);
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) {
      if (IGNORE_DIRS.has(entry)) continue;
      collect(abs, base, acc);
      continue;
    }
    if (IGNORE_FILES.has(entry) || isSecret(entry)) continue;
    const rel = relative(base, abs);
    const bytes = readFileSync(abs);
    const asset = isTextFile(entry)
      ? { text: bytes.toString("utf8") }
      : { b64: bytes.toString("base64") };
    const gz = gzipSync(bytes, { level: 9 }).toString("base64");
    // Only when it earns its keep: the literal in the generated file is what
    // ends up in the binary, so the comparison is against that, not the file.
    const plain = JSON.stringify(asset.text ?? asset.b64).length;
    if (gz.length + 2 < plain * 0.8) {
      delete asset.text;
      delete asset.b64;
      asset.gz = gz;
    }
    // Only the owner-execute bit is carried, and only as 0755 — the shipped
    // permission is a declaration, not whatever the authoring machine had.
    if ((st.mode & 0o100) !== 0) asset.mode = 0o755;
    acc[rel] = asset;
  }
  return acc;
}

const assets = {};
collect(kitDir, repoRoot, assets);
// Flat-root siblings the runtime reads (migrate manifest + kit config).
for (const f of ["portable-manifest.json", "kit.config.json"]) {
  assets[f] = { text: readFileSync(join(repoRoot, f), "utf8") };
}

const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
const sorted = Object.keys(assets).sort();

// The cache is stamped with this digest rather than the package version, so
// editing a kit file during development invalidates the extracted copy even
// though the version has not moved.
const digest = createHash("sha256")
  .update(sorted.map((k) => `${k}\0${assets[k].text ?? assets[k].b64 ?? assets[k].gz}\0${assets[k].mode ?? 0}`).join("\0"))
  .digest("hex")
  .slice(0, 16);

const entries = sorted.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(assets[k])},`).join("\n");
const binaryCount = sorted.filter((k) => assets[k].b64 !== undefined).length;
const gzCount = sorted.filter((k) => assets[k].gz !== undefined).length;

const banner = "// GENERATED by scripts/generate-embedded-kit.mjs — do not edit by hand.\n";
const body =
  banner +
  `// Embedded at ariadnev@${version} — ${sorted.length} kit assets (${binaryCount} binary, ${gzCount} gzipped).\n\n` +
  `export interface EmbeddedAsset {\n` +
  `  /** Text content, verbatim. Mutually exclusive with \`b64\`. */\n` +
  `  text?: string;\n` +
  `  /** Base64 of the raw bytes, for anything that is not text. */\n` +
  `  b64?: string;\n` +
  `  /** Base64 of the gzipped raw bytes, when compression pays for itself. */\n` +
  `  gz?: string;\n` +
  `  /** 0o755 when the source file was executable. */\n` +
  `  mode?: number;\n` +
  `}\n\n` +
  `export const EMBEDDED_VERSION = ${JSON.stringify(version)};\n\n` +
  `/** Digest of the asset map — the cache key, so content changes invalidate it. */\n` +
  `export const EMBEDDED_DIGEST = ${JSON.stringify(digest)};\n\n` +
  `export const EMBEDDED_ASSETS: Record<string, EmbeddedAsset> = {\n${entries}\n};\n`;

writeFileSync(outFile, body);
console.log(
  `embedded ${sorted.length} kit assets (${binaryCount} binary, ${gzCount} gzipped, v${version}, digest ${digest}) -> ${relative(repoRoot, outFile)}`,
);
